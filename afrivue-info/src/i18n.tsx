export const STRINGS: Record<Lang, Dict> = { en, fr, tr, ar };

/* ── Context ── */
export interface I18nValue {
  lang: Lang;
  t: Dict;
  dir: 'ltr' | 'rtl';
  setLang: (l: Lang) => void;
}

export const I18nContext = createContext<I18nValue | null>(null);

export function useI18n(): I18nValue {
  const v = useContext(I18nContext);
  if (!v) throw new Error('useI18n must be used inside I18nContext');
  return v;
}

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('afrivue-lang');
    if (isLang(saved)) return saved;
  } catch {
    /* storage unavailable */
  }
  const nav = (navigator.languages?.[0] || navigator.language || 'en').slice(0, 2).toLowerCase();
  return isLang(nav) ? nav : 'en';
}

export function formatDate(iso: string, lang: Lang, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'long', year: 'numeric' }) {
  return new Intl.DateTimeFormat(LANG_META[lang].locale, opts).format(new Date(iso));
}
